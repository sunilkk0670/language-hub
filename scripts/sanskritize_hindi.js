fs.readdirSync(dir).forEach(file => {
    if (file.startsWith('hi_') && file.endsWith('.json')) {
        const filePath = path.join(dir, file);
        let contentStr = fs.readFileSync(filePath, 'utf8');
        let changed = false;

        for (const [urdu, sanskrit] of Object.entries(dictionary)) {
            const regex = new RegExp(urdu, 'g');
            if (contentStr.includes(urdu)) {
                contentStr = contentStr.replace(regex, sanskrit);
                changed = true;
                // console.log(`Replaced "${urdu}" with "${sanskrit}" in ${file}`);
            }
        }

        if (changed) {
            fs.writeFileSync(filePath, contentStr, 'utf8');
        }
    }
});

